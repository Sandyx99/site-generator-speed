// Fast reimplementation of makefun-site 1.0.0's build(input): the same output tree, byte for byte,
// computed faster. Written from the reference's README and code (vendor/makefun-site/), reimplemented
// here as one dependency-free module: no vendor import at run time.
//
// Where the time goes in the reference: Markdown inline rendering (per-character escapeHtml calls and
// rescans for closers), slugify (NFKD normalise on every title/tag/heading), template interpretation
// (scope-chain lookup per variable, repeated renders of the same header/nav/card). The optimisations:
//  - inline(): one scan, plain runs escaped in bulk, closers found with indexOf (backslash parity
//    preserved), recursion only for nested spans.
//  - slugify(): ASCII fast path (NFKD + mark-strip is the identity on ASCII) plus a per-case memo.
//  - renderMarkdown(): blocks lexed and rendered in one pass, no token objects.
//  - parseFrontMatter(): the close line found with indexOf instead of splitting the whole body.
//  - templates: includes memoised on the values of the included template's free names (pure renders
//    shared: every post's card, the constant header/nav), templates whose free names are only
//    site/tags/recent rendered once per case.
// All caches are created fresh inside run(), so one case never affects another.

